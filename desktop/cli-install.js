import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// The `ph` command for the installed app.
//
// A packaged app cannot assume Node is on PATH, but its own executable is one:
// `ELECTRON_RUN_AS_NODE=1 PeerHub.exe script.mjs ...` runs the CLI in a plain
// Node process. Installing the command therefore means copying the CLI (and the
// one module it imports) into a stable per-user folder, writing thin shims that
// point back at this executable, and putting that folder on the user PATH.
//
// Everything is regenerated on every launch — only when the content changed — so
// an upgrade, a reinstall into another folder, or a moved app can never leave a
// shim pointing at a binary that is gone.
//
// Shims: Windows gets `ph.cmd` (cmd.exe, PowerShell) and `ph` (a POSIX shell
// script, because Git Bash does not consult PATHEXT). POSIX gets the shell
// script alone. Both names `ph` and `peerhub` are installed, so the command is
// the same one the npm bin defines.
//
// PEERHUB_CLI_NO_PATH=1 skips the PATH edit (tests, locked-down machines); the
// shims are still written and `cliInstallReport()` tells the user the folder to
// add by hand.

const CLI_FILE = 'peerhub.mjs';
const SHARED_FILE = 'data-dir.js';
const COMMANDS = ['ph', 'peerhub'];

function localAppData() {
	return process.env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local');
}

/** Fixed per-user folder for the shims and the copied CLI. Not the data dir:
 *  `PEERHUB_DATA_DIR` must not move the command around. */
export function toolsDir() {
	if (process.platform === 'win32') return path.join(localAppData(), 'PeerHub');
	return path.join(os.homedir(), '.peerhub');
}

export function cliPaths() {
	const tools = toolsDir();
	return {
		tools,
		binDir: path.join(tools, 'bin'),
		cliDir: path.join(tools, 'cli'),
		sharedDir: path.join(tools, 'shared'),
		// Without this marker the copied `shared/data-dir.js` inherits the
		// package.json of whatever directory the user's home happens to be in and
		// is reparsed as ESM with a warning on every single command.
		manifest: path.join(tools, 'package.json')
	};
}

function writeIfChanged(file, content, mode) {
	let current = null;
	try {
		current = fs.readFileSync(file, 'utf8');
	} catch {
		// First install.
	}
	if (current !== content) fs.writeFileSync(file, content);
	if (mode) {
		try {
			fs.chmodSync(file, mode);
		} catch {
			// Windows has no meaningful mode; the file runs through cmd.exe.
		}
	}
	return current !== content;
}

function cmdShim(exe, script, version) {
	return [
		'@echo off',
		`rem Generated by PeerHub ${version} - rewritten on every launch, do not edit.`,
		'setlocal EnableExtensions',
		'set "ELECTRON_RUN_AS_NODE=1"',
		`"${exe}" "${script}" %*`,
		'exit /b %ERRORLEVEL%',
		''
	].join('\r\n');
}

// Forward slashes on purpose: the same file is read by Git Bash, which mangles
// backslashes in arguments on their way to a Windows executable.
function shShim(exe, script, version) {
	return [
		'#!/bin/sh',
		`# Generated by PeerHub ${version} - rewritten on every launch, do not edit.`,
		'# The app executable doubles as a Node runtime.',
		`ELECTRON_RUN_AS_NODE=1 exec "${exe}" "${script}" "$@"`,
		''
	].join('\n');
}

function toPosix(file) {
	return file.replace(/\\/g, '/');
}

/** The file a user's Explorer/Start-menu shortcut points at, which is what a
 *  shim must keep working across upgrades. Linux AppImages run from a temporary
 *  mount, so use the image itself (`$APPIMAGE`) rather than the mounted copy. */
function stableExecutable(execPath) {
	if (process.platform === 'linux' && process.env.APPIMAGE) return process.env.APPIMAGE;
	return execPath;
}

function readUserPath() {
	const out = execFileSync('reg', ['query', 'HKCU\\Environment', '/v', 'Path'], {
		encoding: 'utf8',
		windowsHide: true
	});
	const line = out.split(/\r?\n/).find((row) => /^\s+Path\s+REG_/i.test(row));
	if (!line) throw new Error('HKCU\\Environment has no Path value');
	const match = /^\s+Path\s+(REG_[A-Z_]+)\s+(.*)$/i.exec(line);
	if (!match) throw new Error('could not parse HKCU\\Environment Path');
	return { type: match[1], value: match[2].trim() };
}

function normaliseEntry(entry) {
	return entry
		.trim()
		.replace(/[\\/]+$/, '')
		.toLowerCase();
}

// A PATH edit only reaches processes started afterwards, and only if Explorer
// re-reads its environment: without the broadcast, terminals launched from the
// Start menu keep the old PATH even after a reboot-free install.
function broadcastEnvironmentChange() {
	const script = [
		'$sig = \'[DllImport("user32.dll")] public static extern IntPtr SendMessageTimeout(IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam, uint fuFlags, uint uTimeout, out UIntPtr lpdwResult);\'',
		'Add-Type -Namespace PeerHub -Name Native -MemberDefinition $sig',
		'$r = [UIntPtr]::Zero',
		'[PeerHub.Native]::SendMessageTimeout([IntPtr]0xffff, 0x001A, [UIntPtr]::Zero, "Environment", 2, 1000, [ref]$r) | Out-Null'
	].join('; ');
	try {
		execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', script], {
			stdio: 'ignore',
			windowsHide: true
		});
	} catch {
		// Advisory only: the PATH value is already written.
	}
}

/**
 * `%LOCALAPPDATA%\Microsoft\WindowsApps` is on the default user PATH and, unlike
 * a folder appended a minute ago, it is already inside the environment of every
 * terminal that was open before the install. Mirroring the shims there is what
 * makes `ph` answer in those terminals without a restart. Best effort: skipped
 * when the folder is missing, not on PATH, or not writable, and removed again
 * by `--uninstall-cli`.
 */
function mirrorDir() {
	if (process.platform !== 'win32') return null;
	if (process.env.PEERHUB_CLI_NO_PATH === '1') return null;

	const dir = path.join(localAppData(), 'Microsoft', 'WindowsApps');
	let current;
	try {
		current = readUserPath();
	} catch {
		return null;
	}
	if (!current.value.split(';').some((entry) => normaliseEntry(entry) === normaliseEntry(dir))) {
		return null;
	}
	try {
		if (!fs.statSync(dir).isDirectory()) return null;
	} catch {
		return null;
	}
	return dir;
}

function removeOwnedShim(file) {
	try {
		if (fs.readFileSync(file, 'utf8').includes('Generated by PeerHub')) fs.unlinkSync(file);
	} catch {
		// Not ours or already gone.
	}
}

function ensureUserPath(binDir) {
	if (process.platform !== 'win32') return { changed: false };
	if (process.env.PEERHUB_CLI_NO_PATH === '1') return { changed: false };

	let current;
	try {
		current = readUserPath();
	} catch (err) {
		return { changed: false, error: err?.message ?? String(err) };
	}

	const entries = current.value.split(';').filter((entry) => entry.trim());
	if (entries.some((entry) => normaliseEntry(entry) === normaliseEntry(binDir))) {
		return { changed: false };
	}

	const type = current.type === 'REG_SZ' ? 'REG_SZ' : 'REG_EXPAND_SZ';
	try {
		execFileSync(
			'reg',
			[
				'add',
				'HKCU\\Environment',
				'/v',
				'Path',
				'/t',
				type,
				'/d',
				[...entries, binDir].join(';'),
				'/f'
			],
			{ stdio: 'ignore', windowsHide: true }
		);
	} catch (err) {
		return { changed: false, error: err?.message ?? String(err) };
	}
	broadcastEnvironmentChange();
	return { changed: true };
}

function removeUserPath(binDir) {
	if (process.platform !== 'win32') return { changed: false };

	let current;
	try {
		current = readUserPath();
	} catch (err) {
		return { changed: false, error: err?.message ?? String(err) };
	}

	const entries = current.value.split(';').filter((entry) => entry.trim());
	const kept = entries.filter((entry) => normaliseEntry(entry) !== normaliseEntry(binDir));
	if (kept.length === entries.length) return { changed: false };

	const type = current.type === 'REG_SZ' ? 'REG_SZ' : 'REG_EXPAND_SZ';
	try {
		execFileSync(
			'reg',
			['add', 'HKCU\\Environment', '/v', 'Path', '/t', type, '/d', kept.join(';'), '/f'],
			{ stdio: 'ignore', windowsHide: true }
		);
	} catch (err) {
		return { changed: false, error: err?.message ?? String(err) };
	}
	broadcastEnvironmentChange();
	return { changed: true };
}

/** Copy the CLI out of the app bundle and (re)write the shims. Never throws. */
export function installCli({ root, execPath = process.execPath, version = '' }) {
	const { binDir, cliDir, sharedDir, manifest } = cliPaths();
	const cliSource = path.join(root, 'cli', CLI_FILE);
	const sharedSource = path.join(root, 'shared', SHARED_FILE);

	try {
		const cli = fs.readFileSync(cliSource, 'utf8');
		const shared = fs.readFileSync(sharedSource, 'utf8');

		fs.mkdirSync(cliDir, { recursive: true });
		fs.mkdirSync(sharedDir, { recursive: true });
		fs.mkdirSync(binDir, { recursive: true });
		writeIfChanged(manifest, JSON.stringify({ type: 'module', private: true }, null, '\t') + '\n');
		writeIfChanged(path.join(cliDir, CLI_FILE), cli);
		writeIfChanged(path.join(sharedDir, SHARED_FILE), shared);

		const exe = stableExecutable(execPath);
		const script = path.join(cliDir, CLI_FILE);
		const mirror = mirrorDir();
		const shimDirs = mirror ? [binDir, mirror] : [binDir];
		for (const dir of shimDirs) {
			if (dir !== binDir) fs.mkdirSync(dir, { recursive: true });
			for (const name of COMMANDS) {
				if (process.platform === 'win32') {
					writeIfChanged(path.join(dir, `${name}.cmd`), cmdShim(exe, script, version));
					writeIfChanged(
						path.join(dir, name),
						shShim(toPosix(exe), toPosix(script), version),
						0o755
					);
				} else {
					writeIfChanged(path.join(dir, name), shShim(exe, script, version), 0o755);
				}
			}
		}

		const onPath =
			process.platform === 'win32'
				? ensureUserPath(binDir)
				: {
						changed: false,
						error: (process.env.PATH ?? '')
							.split(path.delimiter)
							.map(normaliseEntry)
							.includes(normaliseEntry(binDir))
							? undefined
							: 'folder is not on PATH'
					};

		return {
			ok: true,
			binDir,
			command: path.join(binDir, process.platform === 'win32' ? 'ph.cmd' : 'ph'),
			exec: exe,
			mirrored: Boolean(mirror),
			pathChanged: onPath.changed,
			pathError: onPath.error ?? null
		};
	} catch (err) {
		return { ok: false, binDir, error: err?.message ?? String(err) };
	}
}

/** Remove the shims and the PATH entry. The app itself is untouched. */
export function uninstallCli() {
	const { binDir, cliDir, sharedDir, manifest } = cliPaths();
	const mirror = mirrorDir();
	if (mirror) {
		for (const name of COMMANDS) {
			removeOwnedShim(path.join(mirror, `${name}.cmd`));
			removeOwnedShim(path.join(mirror, name));
		}
	}
	for (const dir of [binDir, cliDir, sharedDir]) {
		try {
			fs.rmSync(dir, { recursive: true, force: true });
		} catch {
			// Locked file / already gone: nothing useful to do here.
		}
	}
	try {
		fs.rmSync(manifest, { force: true });
	} catch {
		// Shared with nothing else; ignore.
	}
	// Leave the folder itself alone: an empty directory on PATH is harmless and
	// it may hold window state later.
	const removed = removeUserPath(binDir);
	return { ok: true, binDir, pathChanged: removed.changed, pathError: removed.error ?? null };
}

/** One-line, human-readable summary for logs and the Help dialog. */
export function describeInstall(result) {
	if (!result?.ok) return `command line tool not installed: ${result?.error ?? 'unknown error'}`;
	const parts = [`ph installed -> ${result.command}`];
	if (result.mirrored) parts.push('also mirrored into WindowsApps for already-open terminals');
	if (result.pathChanged) parts.push('added its folder to your user PATH');
	else if (result.pathError)
		parts.push(`PATH not changed (${result.pathError}); add ${result.binDir}`);
	return parts.join('; ');
}
