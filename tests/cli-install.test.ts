// The compiled `ph` — what the installed app puts on the user's PATH.
//
// The shipped command is a *copy* of `cli/peerhub.mjs` plus the one module it
// imports, rewritten from the app bundle on every launch. That copy is how a
// CLI change reaches a compiled install at all, so these tests assert the copy
// is byte-identical to the source tree rather than merely "present": a stale
// copy is invisible from the source and the only symptom is a binary that
// answers with last release's output.
//
// The real installer is used, pointed at a throwaway local app data folder.
// PEERHUB_CLI_NO_PATH keeps it away from the machine's actual PATH and from the
// WindowsApps mirror — those are the only parts that touch the system.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cliPaths, installCli, toolsDir, uninstallCli } from '../desktop/cli-install.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXE =
	process.platform === 'win32' ? 'D:\\Apps\\PeerHub\\PeerHub.exe' : '/opt/PeerHub/peerhub';

function sandbox() {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'peerhub-cli-'));
	const saved = {
		LOCALAPPDATA: process.env.LOCALAPPDATA,
		HOME: process.env.HOME,
		USERPROFILE: process.env.USERPROFILE,
		PEERHUB_CLI_NO_PATH: process.env.PEERHUB_CLI_NO_PATH
	};

	// toolsDir() reads the environment on every call, so pointing it at a temp
	// folder is enough — no module reload, and the developer's own install is
	// never touched.
	if (process.platform === 'win32') process.env.LOCALAPPDATA = dir;
	else process.env.HOME = dir;
	process.env.USERPROFILE = dir;
	process.env.PEERHUB_CLI_NO_PATH = '1';

	return {
		dir,
		tools: toolsDir(),
		restore() {
			for (const [key, value] of Object.entries(saved)) {
				if (value === undefined) delete process.env[key];
				else process.env[key] = value;
			}
			fs.rmSync(dir, { recursive: true, force: true });
		}
	};
}

test('installing the CLI copies the current cli/peerhub.mjs byte for byte', () => {
	const box = sandbox();
	try {
		const result = installCli({ root: ROOT, execPath: EXE, version: '9.9.9' });
		assert.equal(result.ok, true, result.error);
		assert.equal(result.binDir, path.join(box.tools, 'bin'));

		const { cliDir, sharedDir } = cliPaths();
		assert.equal(
			fs.readFileSync(path.join(cliDir, 'peerhub.mjs'), 'utf8'),
			fs.readFileSync(path.join(ROOT, 'cli', 'peerhub.mjs'), 'utf8'),
			'the installed CLI is the one in the source tree, not an older copy'
		);
		assert.equal(
			fs.readFileSync(path.join(sharedDir, 'data-dir.js'), 'utf8'),
			fs.readFileSync(path.join(ROOT, 'shared', 'data-dir.js'), 'utf8')
		);
		// Both spellings the npm bin defines, so `ph` and `peerhub` behave the same.
		for (const name of ['ph', 'peerhub']) {
			assert.ok(fs.existsSync(path.join(result.binDir, name)), `${name} was not written`);
		}
	} finally {
		box.restore();
	}
});

test('the shims run the copied CLI inside the app executable', () => {
	const box = sandbox();
	try {
		const result = installCli({ root: ROOT, execPath: EXE, version: '9.9.9' });
		const script = path.join(cliPaths().cliDir, 'peerhub.mjs');
		const cmd = fs.readFileSync(path.join(result.binDir, 'ph.cmd'), 'utf8');
		const sh = fs.readFileSync(path.join(result.binDir, 'ph'), 'utf8');

		for (const text of [cmd, sh]) {
			assert.match(text, /ELECTRON_RUN_AS_NODE=1/, 'the app is the only runtime we can count on');
			assert.ok(text.includes('peerhub.mjs'), 'the shim must point at the copied CLI');
			assert.match(text, /Generated by PeerHub/, 'uninstall only removes shims it wrote');
		}
		assert.ok(cmd.includes(EXE), 'ph.cmd calls the app executable');
		assert.ok(sh.includes(EXE.replaceAll('\\', '/')), 'the shell shim uses forward slashes');
		if (process.platform !== 'win32') {
			assert.ok(sh.includes(script), 'a POSIX install has no cmd shim to fall back on');
		}
	} finally {
		box.restore();
	}
});

test('a second install leaves matching files alone', () => {
	const box = sandbox();
	try {
		installCli({ root: ROOT, execPath: EXE, version: '9.9.9' });
		const file = path.join(cliPaths().cliDir, 'peerhub.mjs');
		const before = fs.statSync(file);
		installCli({ root: ROOT, execPath: EXE, version: '9.9.9' });
		const after = fs.statSync(file);
		// Every launch runs this; rewriting the CLI each time would churn the file
		// for no reason and make "did it change?" impossible to answer.
		assert.equal(after.mtimeMs, before.mtimeMs);
	} finally {
		box.restore();
	}
});

test('uninstall removes the copies and the shims', () => {
	const box = sandbox();
	try {
		const result = installCli({ root: ROOT, execPath: EXE, version: '9.9.9' });
		uninstallCli();
		assert.equal(fs.existsSync(cliPaths().cliDir), false);
		assert.equal(fs.existsSync(cliPaths().sharedDir), false);
		assert.equal(fs.existsSync(result.binDir), false);
		assert.equal(fs.existsSync(cliPaths().manifest), false);
	} finally {
		box.restore();
	}
});
